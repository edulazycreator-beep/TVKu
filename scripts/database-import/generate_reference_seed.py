#!/usr/bin/env python3
"""Generate backend/supabase/seed/reference_data.sql (countries, languages).

Countries: ISO 3166-1 (pycountry) with continent from pycountry-convert.
Languages: ISO 639-3 codes that also have an ISO 639-1 code. Further codes are
upserted by the channel importer when a discovered channel uses them.

    pip install pycountry pycountry-convert
    python3 scripts/database-import/generate_reference_seed.py
"""
from __future__ import annotations

import pathlib

import pycountry
import pycountry_convert as pcc

CONTINENTS = {
    "AF": "Africa", "AN": "Antarctica", "AS": "Asia", "EU": "Europe",
    "NA": "North America", "OC": "Oceania", "SA": "South America",
}
# Territories that pycountry-convert does not map.
CONTINENT_OVERRIDES = {
    "AQ": "Antarctica", "TF": "Antarctica", "BV": "Antarctica", "HM": "Antarctica",
    "GS": "Antarctica", "UM": "Oceania", "PN": "Oceania", "EH": "Africa",
    "SX": "North America", "TL": "Asia", "VA": "Europe", "XK": "Europe",
}

OUT = pathlib.Path(__file__).resolve().parents[2] / "backend/supabase/seed/reference_data.sql"


def q(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def continent(alpha2: str) -> str | None:
    if alpha2 in CONTINENT_OVERRIDES:
        return CONTINENT_OVERRIDES[alpha2]
    try:
        return CONTINENTS[pcc.country_alpha2_to_continent_code(alpha2)]
    except KeyError:
        return None


def main() -> None:
    rows = []
    for c in sorted(pycountry.countries, key=lambda c: c.alpha_2):
        name = getattr(c, "common_name", None) or c.name
        region = continent(c.alpha_2)
        rows.append(f"  ({q(c.alpha_2)}, {q(name)}, {q(region) if region else 'null'})")
    # Kosovo is used by broadcasters but is not in ISO 3166-1.
    rows.append("  ('XK', 'Kosovo', 'Europe')")

    langs = sorted(
        ((l.alpha_3, l.name) for l in pycountry.languages if hasattr(l, "alpha_2")),
        key=lambda x: x[0],
    )

    sql = [
        "-- Generated by scripts/database-import/generate_reference_seed.py. Do not edit by hand.",
        "insert into public.countries (code, name, region) values",
        ",\n".join(rows),
        "on conflict (code) do update set name = excluded.name, region = excluded.region;",
        "",
        "insert into public.languages (code, name) values",
        ",\n".join(f"  ({q(code)}, {q(name)})" for code, name in langs),
        "on conflict (code) do update set name = excluded.name;",
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(sql), encoding="utf-8")
    print(f"wrote {OUT} ({len(rows)} countries, {len(langs)} languages)")


if __name__ == "__main__":
    main()
